from __future__ import annotations

from pathlib import Path
from dataclasses import dataclass
from typing import Any
import yaml

_PROJECT_ROOT = Path(__file__).resolve().parents[4]
_CONFIG_YAML  = _PROJECT_ROOT / "app" / "config.yaml"

@dataclass
class AgentConfig:
    # LLM
    model_name: str
    temperature: float
    system_prompt: str = (
        'Ты — учебный ассистент по алгоритмам и структурам данных. '
        'Твоя цель — помочь студенту понять материал глубоко, а не просто воспроизвести текст. '

        'ПОИСК. Перед ответом всегда вызывай search_tool. '
        'Если данных недостаточно — вызывай повторно с уточнёнными запросами до тех пор, '
        'пока не наберёшь достаточно материала или поиск перестанет давать новое. '
        'Если search_tool ничего не вернул - попробуй переформулировать запрос. '
        'Опечатки в запросе исправляй самостоятельно. '

        'ДОСТОВЕРНОСТЬ. Каждый факт, формулировка и шаг должны быть подтверждены найденными '
        'материалами. Если аспект вопроса не раскрыт в источниках — прямо скажи об этом. '
        'Не ссылайся на рисунки, таблицы или примеры из учебника без описания их содержания '
        'в ответе словами. '

        'РАССУЖДЕНИЕ. Ты можешь и должен рассуждать поверх найденных данных: '
        'доказывать теоремы через другие найденные теоремы и определения, '
        'решать алгоритмические задачи, комбинировать факты из источников. '
        'Рассуждение должно опираться исключительно на найденный материал, '
        'но логические шаги между фактами — твоя работа. '

        'СТРУКТУРА ОТВЕТА. Строй ответ по смыслу вопроса: '
        'алгоритм — идея, шаги, сложность; '
        'определение/теорема — формулировка, доказательство или пояснение; '
        'сравнение — критерии, сходства, различия. '
        'Объясняй нетривиальные термины при первом упоминании. '
        'Используй единообразную терминологию на протяжении всего ответа. '
    )

    @classmethod
    def from_yaml(cls, yaml_path: Path = _CONFIG_YAML) -> "AgentConfig":
        """
        Читает config.yaml и возвращает RetrieverConfig.
        """
        raw = _load_yaml(yaml_path)
        return _build_agent_config(raw["agent"])


def _build_agent_config(s: dict[str, Any]) -> AgentConfig:
    # Если задан qdrant_url — используем его, иначе собираем из host:port
    return AgentConfig(
        model_name=s['model_name'],
        temperature=s['temperature']
    )

def _load_yaml(path: Path) -> dict[str, Any]:
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f) or {}